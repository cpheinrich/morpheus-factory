#!/usr/bin/env bash
#
# sub2api PoC — install sub2api (simple mode) via Docker Compose on a Mac.
#
# Idempotent: re-running preserves an existing .env and all data. The compose
# file comes from a pinned upstream commit and is checked against a SHA-256
# before it replaces the installed copy; the application image is pinned by an
# override file. Upgrading is a deliberate edit of the pins below.
#
# Usage:
#   scripts/setup-sub2api.sh [DEPLOY_DIR]
#
# DEPLOY_DIR defaults to ~/sub2api-deploy. It holds the compose files, the .env
# (secrets) and the data directories — deliberately OUTSIDE the repo, because
# the .env contains credentials that must never be committed.
#
# Secrets are generated into .env (mode 600) and never printed. The admin
# password is the ADMIN_PASSWORD line of that file.

set -euo pipefail

# Prerequisites: a working Docker daemon (Colima or Docker Desktop) and the
# compose plugin (`brew install docker-compose` + cliPluginsExtraDirs).
if ! docker compose version >/dev/null 2>&1; then
  echo "error: 'docker compose' not found. Install the compose plugin:" >&2
  echo "  brew install docker-compose" >&2
  echo "  # then add cliPluginsExtraDirs to ~/.docker/config.json (see brew caveats)" >&2
  exit 1
fi

DEPLOY_DIR="${1:-$HOME/sub2api-deploy}"

# --- pins (bump deliberately; see docs/sub2api-poc.md) ---------------------
# Upstream commit of deploy/docker-compose.local.yml and its SHA-256.
COMPOSE_REF="f17918ea1746df840ef766ba43e019629bf7708e"
COMPOSE_SHA256="d8dfd3798fb9e4aea102bbb681d092529aa169337a5fbf003a038a14640c8de1"
COMPOSE_URL="https://raw.githubusercontent.com/Wei-Shaw/sub2api/${COMPOSE_REF}/deploy/docker-compose.local.yml"
# Upstream compose uses weishaw/sub2api:latest; the override pins the release.
IMAGE_TAG="${SUB2API_IMAGE_TAG:-0.2.19}"

# --- values that are safe to commit (no secrets) ---------------------------
BIND_HOST="${BIND_HOST:-0.0.0.0}"
SERVER_PORT="${SERVER_PORT:-8080}"
TZ="${TZ:-America/Los_Angeles}"
ADMIN_EMAIL="${ADMIN_EMAIL:-admin@sub2api.local}"

if [[ ! "$IMAGE_TAG" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
  echo "error: SUB2API_IMAGE_TAG must be a release like 0.2.19, got '$IMAGE_TAG'" >&2
  exit 2
fi

sha256_of() {
  shasum -a 256 "$1" | cut -d' ' -f1
}

umask 077
mkdir -p "$DEPLOY_DIR"
cd "$DEPLOY_DIR"

# --- compose file: pinned commit, verified before install ------------------
if [[ -f docker-compose.local.yml && "$(sha256_of docker-compose.local.yml)" == "$COMPOSE_SHA256" ]]; then
  echo "==> compose file already at pinned ${COMPOSE_REF:0:12}"
else
  echo "==> fetching compose file at ${COMPOSE_REF:0:12}"
  download="$(mktemp docker-compose.local.yml.XXXXXX)"
  trap 'rm -f "$download"' EXIT
  curl -fsSL --max-time 60 "$COMPOSE_URL" -o "$download"
  actual="$(sha256_of "$download")"
  if [[ "$actual" != "$COMPOSE_SHA256" ]]; then
    echo "error: compose file checksum mismatch (expected $COMPOSE_SHA256, got $actual); nothing changed" >&2
    exit 1
  fi
  chmod 644 "$download"
  mv "$download" docker-compose.local.yml
  trap - EXIT
fi

cat > docker-compose.pin.yml <<EOF
# Generated by scripts/setup-sub2api.sh: pins the application image.
services:
  sub2api:
    image: weishaw/sub2api:${IMAGE_TAG}
EOF

# --- generate .env once; never overwrite an existing one -------------------
if [[ ! -f .env ]]; then
  echo "==> generating .env (secrets; not printed)"
  POSTGRES_PASSWORD="$(openssl rand -hex 24)"
  REDIS_PASSWORD="$(openssl rand -hex 24)"
  JWT_SECRET="$(openssl rand -hex 32)"
  TOTP_ENCRYPTION_KEY="$(openssl rand -hex 32)"
  ADMIN_PASSWORD="$(openssl rand -hex 16)"

  cat > .env <<EOF
# sub2api PoC — generated by scripts/setup-sub2api.sh. Do not commit.
BIND_HOST=${BIND_HOST}
SERVER_PORT=${SERVER_PORT}
RUN_MODE=simple
SIMPLE_MODE_AUTO_CREATE_DEFAULT_GROUPS=true
TZ=${TZ}

POSTGRES_USER=sub2api
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
POSTGRES_DB=sub2api
REDIS_PASSWORD=${REDIS_PASSWORD}

ADMIN_EMAIL=${ADMIN_EMAIL}
ADMIN_PASSWORD=${ADMIN_PASSWORD}

JWT_SECRET=${JWT_SECRET}
TOTP_ENCRYPTION_KEY=${TOTP_ENCRYPTION_KEY}
EOF
  unset POSTGRES_PASSWORD REDIS_PASSWORD JWT_SECRET TOTP_ENCRYPTION_KEY ADMIN_PASSWORD
else
  echo "==> .env already exists; leaving its values untouched"
fi
chmod 600 .env

# --- data directories (local-dir compose variant) --------------------------
mkdir -p data postgres_data redis_data

# --- start ----------------------------------------------------------------
COMPOSE=(docker compose -f docker-compose.local.yml -f docker-compose.pin.yml)
echo "==> starting stack (weishaw/sub2api:${IMAGE_TAG})"
"${COMPOSE[@]}" up -d

echo
echo "==> done. Admin UI on port $(grep '^SERVER_PORT=' .env | cut -d= -f2) (bound to $(grep '^BIND_HOST=' .env | cut -d= -f2))"
echo "    login: $(grep '^ADMIN_EMAIL=' .env | cut -d= -f2)"
echo "    password: ADMIN_PASSWORD in $DEPLOY_DIR/.env (not printed)"
echo
echo "    status:  ${COMPOSE[*]} ps"
echo "    logs:    ${COMPOSE[*]} logs -f sub2api"
